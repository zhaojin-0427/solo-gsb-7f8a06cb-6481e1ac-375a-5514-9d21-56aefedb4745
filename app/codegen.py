"""生成桥接 .so 的 C 源码与 GNU 符号版本脚本。

生成的桥：

* 保留旧库 SONAME；
* 按旧布局接参（旧结构体类型原样声明，用 _Static_assert 与旧/新字节大小对齐）；
* 在本地构造新版结构体（允许重排/新增带默认值字段），调用候选库对应版本函数；
* 候选库通过独立文件名 ``$ORIGIN/<独立文件名>`` 加载，并使用独立 dlmopen
  链接命名空间，保证桥接调用绝不回到自身（即使二者 SONAME 相同）；
* 版本化候选符号用 dlvsym 精确取版本；未版本化用 dlsym；
* 客户端需要的每个 GNU 符号版本由版本脚本挂到对应入口。
"""

from __future__ import annotations

import re

from .errors import BridgeError
from .planner import FunctionBridge, StructBridge

_TAG_RE = re.compile(r"[^A-Za-z0-9_.]")


def _c_str(value: str) -> str:
    """把任意字符串安全地编码为 C 字符串字面量内容。"""
    import json
    # json.dumps 的转义集是 C 的超集（双引号/反斜杠/控制字符）
    return json.dumps(value, ensure_ascii=False)


def _c_scalar(kind: str) -> str:
    return {"i32": "int32_t", "f64": "double"}[kind]


def _c_literal(kind: str, value) -> str:
    if kind == "i32":
        return f"INT32_C({int(value)})"
    f = float(value)
    # repr 给出最短可往返表示；inf/nan 已在规划阶段排除
    return repr(f)


def generate_source(fbs: list[FunctionBridge], candidate_file_name: str) -> str:
    L: list[str] = []
    a = L.append

    a("/* Generated by compat-bridge service. Do not edit. */")
    a("#define _GNU_SOURCE")
    a("#include <stdint.h>")
    a("#include <stddef.h>")
    a("#include <dlfcn.h>")
    a("#include <stdio.h>")
    a("#include <stdlib.h>")
    a("#include <string.h>")
    a("")
    a(f"#define CANDIDATE_FILE_NAME {_c_str(candidate_file_name)}")
    a("")

    # ---- 结构体定义（旧/新两套布局）------------------------------------
    emitted_old: set[str] = set()
    emitted_new: set[str] = set()
    all_structs: list[tuple[str, StructBridge, int]] = []  # (size_side...)
    # 需要旧尺寸用于 _Static_assert：从 FieldDelta 无法直接拿旧大小，
    # 规划阶段未记录；旧大小 = 最后一个旧字段 offset + 宽度。
    for fb in fbs:
        for p in fb.parameters:
            sb: StructBridge | None = p["struct"]
            if sb is None:
                continue
            old_fields = [f for f in sb.fields if f.status == "kept"]
            old_size = max(f.old_offset + (4 if f.scalar == "i32" else 8) for f in old_fields)
            all_structs.append((old_size, sb))

    for old_size, sb in all_structs:
        if sb.old_name not in emitted_old:
            emitted_old.add(sb.old_name)
            a(f"struct __old_{sb.old_name} {{")
            for f in [x for x in sb.fields if x.status == "kept"]:
                a(f"    {_c_scalar(f.scalar)} {f.name};")
            a("};")
            a(f"_Static_assert(sizeof(struct __old_{sb.old_name}) == {old_size},")
            a(f'    "old layout of {sb.old_name} mismatch");')
            a("")
        if sb.new_name not in emitted_new:
            emitted_new.add(sb.new_name)
            a(f"struct __new_{sb.new_name} {{")
            # 按候选库 DWARF 中的偏移顺序输出，真实反映重排后的新版布局
            for f in sorted(sb.fields, key=lambda x: x.new_offset):
                a(f"    {_c_scalar(f.scalar)} {f.name};")
            a("};")
            a(f"_Static_assert(sizeof(struct __new_{sb.new_name}) == {sb.byte_size},")
            a(f'    "new layout of {sb.new_name} mismatch");')
            a("")

    # ---- 函数指针类型（候选库侧：使用新版结构体布局）---------------------
    for fb in fbs:
        params = []
        for p in fb.parameters:
            if p["kind"] in ("i32", "f64"):
                params.append(f"{_c_scalar(p['kind'])} {p['name']}")
            else:
                params.append(f"struct __new_{p['struct'].new_name} {p['name']}")
        ret = "void" if fb.return_kind == "void" else _c_scalar(fb.return_kind)
        a(f"typedef {ret} (*{fb.name}_fn_t)({', '.join(params) if params else 'void'});")
    a("")

    # ---- 候选库句柄与入口指针 -------------------------------------------
    for fb in fbs:
        a(f"static {fb.name}_fn_t p_{fb.name};")
    a("")
    a("static void *cand_handle;")
    a("")
    a("static void *resolve_sym(const char *sym, const char *ver) {")
    a("    void *p = ver ? dlvsym(cand_handle, sym, ver) : dlsym(cand_handle, sym);")
    a("    if (p == NULL) {")
    a('        fprintf(stderr, "compat bridge: cannot resolve %s%s%s: %s\\n",')
    a('                sym, ver ? "@" : "", ver ? ver : "", dlerror());')
    a("        abort();")
    a("    }")
    a("    return p;")
    a("}")
    a("")
    a("__attribute__((constructor))")
    a("static void bridge_init(void) {")
    a("    char path[4096];")
    a('    Dl_info self;')
    a('    if (dladdr((const void *)&bridge_init, &self) == 0 || self.dli_fname[0] != \'/\') {')
    a('        fprintf(stderr, "compat bridge: cannot locate own file\\n");')
    a("        abort();")
    a("    }")
    a("    size_t dlen = 0;")
    a("    {")
    a("        const char *slash = strrchr(self.dli_fname, '/');")
    a("        dlen = (size_t)(slash - self.dli_fname);")
    a("    }")
    a("    if (dlen + 1 + sizeof(CANDIDATE_FILE_NAME) >= sizeof(path)) {")
    a('        fprintf(stderr, "compat bridge: install path too long\\n");')
    a("        abort();")
    a("    }")
    a("    memcpy(path, self.dli_fname, dlen);")
    a('    path[dlen] = \'/\';')
    a("    memcpy(path + dlen + 1, CANDIDATE_FILE_NAME, sizeof(CANDIDATE_FILE_NAME));")
    a("    /* 独立 dlmopen 命名空间：即使候选库与本桥 SONAME 相同，")
    a("       符号查找也严格落在候选库自身，绝不回到桥接。 */")
    a("    cand_handle = dlmopen(LM_ID_NEWLM, path, RTLD_NOW | RTLD_LOCAL | RTLD_DEEPBIND);")
    a("    if (cand_handle == NULL) {")
    a('        fprintf(stderr, "compat bridge: dlmopen(%s) failed: %s\\n", path, dlerror());')
    a("        abort();")
    a("    }")
    for fb in fbs:
        ver = "NULL" if fb.candidate_version is None else _c_str(fb.candidate_version)
        a(f"    p_{fb.name} = ({fb.name}_fn_t)resolve_sym({_c_str(fb.name)}, {ver});")
    a("}")
    a("")

    # ---- 入口包装 -------------------------------------------------------
    for fb in fbs:
        params = []
        for p in fb.parameters:
            if p["kind"] in ("i32", "f64"):
                params.append(f"{_c_scalar(p['kind'])} {p['name']}")
            else:
                params.append(f"struct __old_{p['struct'].old_name} {p['name']}")
        ret = "void" if fb.return_kind == "void" else _c_scalar(fb.return_kind)
        a(f"{ret} {fb.name}({', '.join(params) if params else 'void'}) {{")

        call_args: list[str] = []
        for p in fb.parameters:
            if p["kind"] in ("i32", "f64"):
                call_args.append(p["name"])
            else:
                sb: StructBridge = p["struct"]
                local = f"__new_{p['name']}"
                a(f"    struct __new_{sb.new_name} {local};")
                for f in sb.fields:
                    if f.status == "kept":
                        a(f"    {local}.{f.name} = {p['name']}.{f.name};")
                    else:
                        a(f"    {local}.{f.name} = {_c_literal(f.scalar, f.default)};")
                call_args.append(local)

        if fb.return_kind == "void":
            a(f"    p_{fb.name}({', '.join(call_args)});")
        else:
            a(f"    return p_{fb.name}({', '.join(call_args)});")
        a("}")
        a("")

    return "\n".join(L)


def generate_version_script(fbs: list[FunctionBridge]) -> str:
    """每个客户端所需符号版本一个节点；其余全部 local。

    同名函数被多个版本引用的情况在规划阶段已被拒绝（每个入口只服务一个版本）。
    """

    L: list[str] = []
    used: set[str] = set()
    for fb in fbs:
        tag = fb.client_version
        if tag is None:
            continue
        if not tag or _TAG_RE.search(tag):
            raise BridgeError(f"客户端符号版本名 {tag!r} 含非法字符（无法写入版本脚本）")
        if tag in used:
            continue
        used.add(tag)
        names = sorted({x.name for x in fbs if x.client_version == tag})
        a = L.append
        a(f"{tag} {{")
        a("    global:")
        for n in names:
            a(f"        {n};")
        a("};")
        a("")

    # 未版本化入口：放到固定全局节点（无版本号绑定，客户端的未版本化引用即可绑定）
    unversioned = sorted({fb.name for fb in fbs if fb.client_version is None})
    if unversioned:
        L.append("BRIDGE_GLOBAL {")
        L.append("    global:")
        for n in unversioned:
            L.append(f"        {n};")
        L.append("};")
        L.append("")

    # 未列出的符号全部本地化（libc 导入不受影响）。
    # 注意：脚本里必须先有承载 global 的节点，单独的 local:* 节点会把入口也本地化。
    L.append("BRIDGE_LOCAL {")
    L.append("    local: *;")
    L.append("};")
    L.append("")
    return "\n".join(L)
